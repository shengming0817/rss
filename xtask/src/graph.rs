#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Options {
    assembly: String,
    format: Option<Format>,
    check: bool,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            assembly: "runtime".into(),
            format: None,
            check: false,
        }
    }
}

impl Options {
    pub(crate) fn check_runtime() -> Self {
        Self {
            check: true,
            ..Self::default()
        }
    }
}

pub(crate) fn parse(args: &[&str]) -> Result<Options> {
    let Some((&"assembly", rest)) = args.split_first() else {
        bail!(
            "未知 graph 子命令；用法: cargo xtask graph assembly [--assembly <name>] [--format mermaid|json] [--check]"
        )
    };
    let mut options = Options::default();
    let mut assembly_set = false;
    let mut it = rest.iter();
    while let Some(&arg) = it.next() {
        match arg {
            "--check" if !options.check => options.check = true,
            "--check" => bail!("graph assembly 参数 --check 重复"),
            "--assembly" if !assembly_set => {
                let value = next_value(&mut it, "--assembly")?;
                validate_name(value)?;
                options.assembly = (*value).to_string();
                assembly_set = true;
            }
            "--assembly" => bail!("graph assembly 参数 --assembly 重复"),
            "--format" if options.format.is_none() => {
                options.format = Some(match next_value(&mut it, "--format")? {
                    "mermaid" => Format::Mermaid,
                    "json" => Format::Json,
                    value => bail!("未知 graph format `{value}`；仅支持 mermaid|json"),
                });
            }
            "--format" => bail!("graph assembly 参数 --format 重复"),
            value => bail!("graph assembly 未知参数: {value}"),
        }
    }
    if options.check && options.assembly != "runtime" {
        bail!("--check 仅适用于 committed runtime assembly graph");
    }
    if options.check && options.format.is_some() {
        bail!("--check 必须同时校验 Mermaid/JSON 双产物，禁止与 --format 组合");
    }
    Ok(options)
}

fn next_value<'a>(it: &mut std::slice::Iter<'a, &str>, flag: &str) -> Result<&'a str> {
    let value = *it.next().with_context(|| format!("{flag} 缺值"))?;
    if value.starts_with("--") {
        bail!("{flag} 缺值（收到下一个 flag `{value}`）");
    }
    Ok(value)
}

fn validate_name(name: &str) -> Result<()> {
    if name.is_empty()
        || !name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        bail!("assembly name 仅允许非空 lowercase ASCII、数字与连字符");
    }
    Ok(())
}

pub(crate) fn run(options: &Options) -> Result<()> {
    generate_root(&crate::workspace_root()?, options)
}

