fn edge_label(kind: EdgeKind) -> &'static str {
    match kind {
        EdgeKind::Contains => "contains",
        EdgeKind::Exposes => "exposes",
        EdgeKind::BindsListener => "binds listener",
        EdgeKind::DeclaresProvider => "declares provider",
        EdgeKind::RequiresCapability => "requires capability",
        EdgeKind::ContributesOutput => "contributes output",
        EdgeKind::DeclaresShape => "declares output shape",
        EdgeKind::ShapeIncludes => "declared shape includes",
        EdgeKind::Publishes => "publishes",
        EdgeKind::Subscribes => "subscribes",
    }
}
fn escape_mermaid(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn generate_root(root: &Path, options: &Options) -> Result<()> {
    let model = build_model(root, &options.assembly)?;
    let base = if options.assembly == "runtime" {
        root.join("docs/architecture/generated/runtime-assembly")
    } else {
        root.join("target/xtask")
            .join(format!("{}-assembly", options.assembly))
    };
    let formats: &[Format] = match options.format {
        Some(Format::Json) => &[Format::Json],
        Some(Format::Mermaid) => &[Format::Mermaid],
        None => &[Format::Mermaid, Format::Json],
    };
    let mut targets = Vec::new();
    for format in formats {
        let (path, content) = match format {
            Format::Json => (base.with_extension("json"), render_json(&model)?),
            Format::Mermaid => (base.with_extension("mmd"), render_mermaid(&model)?),
        };
        ensure_no_symlinks(root, &path)?;
        let actual = if options.check || path.exists() {
            let actual = fs::read_to_string(&path).with_context(|| {
                format!(
                    "缺少 committed graph {}",
                    relative(root, &path).unwrap_or_else(|_| path.display().to_string())
                )
            })?;
            ensure_owned(&path, &actual, *format)?;
            Some(actual)
        } else {
            None
        };
        targets.push((path, content, actual));
    }
    if options.check {
        for (path, content, actual) in &targets {
            let actual = actual
                .as_deref()
                .context("check target missing after planning")?;
            if actual != content {
                bail!(
                    "assembly graph 派生漂移: {}；运行 `cargo xtask graph assembly`",
                    relative(root, path)?
                );
            }
        }
        eprintln!("graph assembly --check: 无漂移");
        return Ok(());
    }
    for (path, content, actual) in targets {
        if actual.as_deref() != Some(content.as_str()) {
            atomic_write(&path, content.as_bytes())?;
            eprintln!("generated {}", relative(root, &path)?);
        }
    }
    Ok(())
}

fn ensure_owned(path: &Path, content: &str, format: Format) -> Result<()> {
    let owned = match format {
        Format::Mermaid => content.starts_with(OWNERSHIP_MARKER_MERMAID),
        Format::Json => serde_json::from_str::<serde_json::Value>(content)
            .ok()
            .and_then(|v| {
                v.get("generatedBy")
                    .and_then(|v| v.as_str())
                    .map(|v| v == GENERATED_BY)
            })
            .unwrap_or(false),
    };
    if !owned {
        bail!("拒绝覆盖或检查非本生成器文件：{}", path.display());
    }
    Ok(())
}

fn reject_symlink(path: &Path) -> Result<()> {
    if fs::symlink_metadata(path).is_ok_and(|m| m.file_type().is_symlink()) {
        bail!("graph 路径禁止符号链接：{}", path.display());
    }
    Ok(())
}
fn ensure_no_symlinks(root: &Path, path: &Path) -> Result<()> {
    let rel = path
        .strip_prefix(root)
        .context("graph 输出越过 workspace")?;
    let mut current = root.to_path_buf();
    for c in rel.components() {
        current.push(c);
        reject_symlink(&current)?;
    }
    Ok(())
}
fn relative(root: &Path, path: &Path) -> Result<String> {
    Ok(path
        .strip_prefix(root)
        .context("source 越过 workspace")?
        .components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/"))
}

fn atomic_write(path: &Path, content: &[u8]) -> Result<()> {
    let parent = path.parent().context("graph target 无父目录")?;
    fs::create_dir_all(parent)?;
    let tmp = parent.join(format!(
        ".graph.tmp-{}-{}",
        std::process::id(),
        TEMP_SEQUENCE.fetch_add(1, Ordering::Relaxed)
    ));
    let result = (|| -> Result<()> {
        let mut f = OpenOptions::new().create_new(true).write(true).open(&tmp)?;
        f.write_all(content)?;
        f.sync_all()?;
        drop(f);
        fs::rename(&tmp, path)?;
        File::open(parent)?.sync_all()?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}

