-- Harden tenant RLS policies for empty `rss.tenant_id` custom GUC.
--
-- `current_setting('rss.tenant_id', true)` can yield an empty string after a
-- prior transaction-scoped SET LOCAL ends. Casting that value directly to uuid
-- errors before the policy can fail closed. Keep the existing policy names and
-- update the predicate in a forward-only migration rather than rewriting older
-- committed migrations.

ALTER POLICY tenant_isolation ON sessions
    USING (tenant_id = NULLIF(current_setting('rss.tenant_id', true), '')::uuid)
    WITH CHECK (tenant_id = NULLIF(current_setting('rss.tenant_id', true), '')::uuid);

